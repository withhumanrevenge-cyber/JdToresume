"""Word (.docx) versions of the resume and cover letter, built from the same render data as the PDFs.

Some application portals only take .docx, and some recruiters prefer it. The layout mirrors
`templates/classic.typ` and `templates/cover_letter.typ` and follows the same ATS rules (ats-compliance skill §2):
one column of plain paragraphs in reading order, Word's built-in "Heading 1" for section headings (parsers and
screen readers rely on it), the built-in "List Bullet" style for bullets, contact details in the body rather
than the page header, visible URLs, and no tables, text boxes, shapes or images.

The input is the dict from `build_resume_document` / `build_cover_letter_document`, so the .docx says exactly
what the PDF says, including any bullets the fit-to-page loop dropped.
"""

from __future__ import annotations

import io
from datetime import UTC, datetime
from typing import Any

from docx import Document
from docx.document import Document as DocxDocument
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.opc.constants import RELATIONSHIP_TYPE
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Inches, Length, Mm, Pt, RGBColor
from docx.text.paragraph import Paragraph

FONT = "Calibri"
SEP = "  |  "
_PAPER: dict[str, tuple[Length, Length]] = {"us-letter": (Inches(8.5), Inches(11)), "a4": (Mm(210), Mm(297))}


def resume_docx(document: dict[str, Any]) -> bytes:
    header = document["header"]
    doc = _new_document(document["page"]["paper"], margin=Inches(0.6), size=10.5, paragraph_gap=Pt(3),
                        title=f"{header['name']} – Resume", author=header["name"])

    _centered(doc, header["name"], size=20, bold=True)
    if header["headline"]:
        _centered(doc, header["headline"], size=11)
    _contact_line(doc, header["contact"])

    for section in document["sections"]:
        doc.add_paragraph(section["heading"], style="Heading 1")
        kind = section["kind"]
        if kind == "summary":
            doc.add_paragraph(section["text"])
        elif kind in ("experience", "projects", "education"):
            for entry in section["entries"]:
                _entry(doc, entry)
        elif kind == "skills":
            for group in section["groups"]:
                paragraph = doc.add_paragraph()
                paragraph.add_run(f"{group['label']}:").bold = True
                paragraph.add_run(f" {group['items']}")
        elif kind == "certifications":
            for item in section["items"]:
                doc.add_paragraph(item, style="List Bullet")
    return _save(doc)


def cover_letter_docx(document: dict[str, Any]) -> bytes:
    name = document["header"]["name"]
    doc = _new_document(document["page"]["paper"], margin=Inches(0.9), size=11, paragraph_gap=Pt(10),
                        title=f"{name} – Cover Letter", author=name)

    _centered(doc, name, size=18, bold=True)
    _contact_line(doc, document["header"]["contact"])

    doc.add_paragraph(document["date"]).paragraph_format.space_before = Pt(18)
    if document["recipient"]:
        _lines(doc, document["recipient"])
    doc.add_paragraph(document["salutation"])
    for text in document["paragraphs"]:
        doc.add_paragraph(text)
    _lines(doc, [document["closing"], document["signature"]])
    return _save(doc)


# --------------------------------------------------------------------------- building blocks

def _new_document(paper: str, *, margin: Length, size: float, paragraph_gap: Length, title: str,
                  author: str) -> DocxDocument:
    doc = Document()
    section = doc.sections[0]
    section.page_width, section.page_height = _PAPER[paper]
    section.left_margin = section.right_margin = section.top_margin = section.bottom_margin = margin

    normal = doc.styles["Normal"]
    _set_font(normal, size)
    normal.paragraph_format.space_before = Pt(0)
    normal.paragraph_format.space_after = paragraph_gap
    normal.paragraph_format.line_spacing = 1.0

    heading = doc.styles["Heading 1"]
    _set_font(heading, 12, bold=True)
    heading.paragraph_format.space_before = Pt(10)
    heading.paragraph_format.space_after = Pt(3)

    bullet = doc.styles["List Bullet"]
    bullet.paragraph_format.space_after = Pt(2)

    # The blank template says "python-docx", 2013 and "generated by python-docx"; describe this file instead.
    props = doc.core_properties
    props.title = title
    props.author = props.last_modified_by = author
    props.comments = props.subject = props.keywords = props.category = ""
    props.created = props.modified = datetime.now(UTC)
    props.revision = 1
    return doc


def _set_font(style, size: float, *, bold: bool | None = None) -> None:
    style.font.name = FONT
    style.font.size = Pt(size)
    style.font.bold = bold
    style.font.color.rgb = RGBColor(0, 0, 0)
    # The template's headings use theme fonts, and Word lets a theme font win over the name set above.
    fonts = style.element.rPr.rFonts
    for attribute in ("w:asciiTheme", "w:hAnsiTheme", "w:eastAsiaTheme", "w:cstheme"):
        fonts.attrib.pop(qn(attribute), None)


def _centered(doc: DocxDocument, text: str, *, size: float, bold: bool = False) -> None:
    paragraph = doc.add_paragraph()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    paragraph.paragraph_format.space_after = Pt(0)
    run = paragraph.add_run(text)
    run.font.size = Pt(size)
    run.bold = bold or None


def _contact_line(doc: DocxDocument, items: list[dict[str, str | None]]) -> None:
    """Email | phone | city | links, centred, in the body (never the page header, which parsers skip)."""
    paragraph = doc.add_paragraph()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    paragraph.paragraph_format.space_after = Pt(6)
    for index, item in enumerate(items):
        if index:
            paragraph.add_run(SEP)
        if item["url"]:
            _hyperlink(paragraph, item["text"], item["url"])
        else:
            paragraph.add_run(item["text"])


def _entry(doc: DocxDocument, entry: dict[str, Any]) -> None:
    """Title, org / dates | location | link / detail / bullets: the same lines, in the same order, as the PDF."""
    title = doc.add_paragraph()
    title.paragraph_format.space_before = Pt(6)
    title.paragraph_format.space_after = Pt(0)
    title.paragraph_format.keep_with_next = True
    title.add_run(entry["title"]).bold = True
    if entry["org"]:
        title.add_run(f", {entry['org']}")

    meta = [part for part in (entry["dates"], entry["location"]) if part]
    if meta or entry["link"]:
        line = doc.add_paragraph()
        line.paragraph_format.space_after = Pt(0)
        line.paragraph_format.keep_with_next = True
        line.add_run(SEP.join(meta)).italic = True
        if entry["link"]:
            if meta:
                line.add_run(SEP).italic = True
            _hyperlink(line, entry["link"]["text"], entry["link"]["url"], italic=True)

    if entry["detail"]:
        detail = doc.add_paragraph(entry["detail"])
        detail.paragraph_format.keep_with_next = True
    for text in entry["bullets"]:
        doc.add_paragraph(text, style="List Bullet")


def _lines(doc: DocxDocument, lines: list[str]) -> Paragraph:
    """One paragraph with a line break between lines (an address block, a sign-off)."""
    paragraph = doc.add_paragraph()
    for index, text in enumerate(lines):
        run = paragraph.add_run(text)
        if index < len(lines) - 1:
            run.add_break()
    return paragraph


def _hyperlink(paragraph: Paragraph, text: str, url: str, *, italic: bool = False) -> None:
    """A clickable link whose visible text is the address itself. python-docx has no API for adding links, so
    the run is created normally and then moved inside a <w:hyperlink> element."""
    relationship_id = paragraph.part.relate_to(url, RELATIONSHIP_TYPE.HYPERLINK, is_external=True)
    link = OxmlElement("w:hyperlink")
    link.set(qn("r:id"), relationship_id)
    run = paragraph.add_run(text)
    run.italic = italic or None
    link.append(run._r)  # moves the run out of the paragraph and into the link
    paragraph._p.append(link)


def _save(doc: DocxDocument) -> bytes:
    buffer = io.BytesIO()
    doc.save(buffer)
    return buffer.getvalue()
